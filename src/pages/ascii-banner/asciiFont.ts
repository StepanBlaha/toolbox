/** Returns the glyph rows for a character, falling back to a blank space
 *  glyph for anything not in the font (so unsupported chars render as gaps
 *  instead of throwing). */
export function getGlyph(char: string): string[] {
  return FONT[char] ?? FONT[" "];
}
